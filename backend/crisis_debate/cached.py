"""Replay a recorded run through the same Backend interface as a live provider.

This is the fallback when no OpenAI key is present. It is not a mock in the
usual sense: the text it serves was generated by a model and recorded, so the
pipeline downstream of it behaves exactly as it does live. What is *not* real is
the latency, which is modelled, and the fact that nothing is being decided now.

Two rules keep it honest:

* It serves responses in the order the pipeline asks for them, keyed by the
  schema requested. If the pipeline changes shape, the replay runs out of
  recorded turns and raises rather than inventing one.
* Every run it produces is labelled `cached` all the way into the results table,
  so a recorded run can never be mistaken for a measurement.
"""
from __future__ import annotations

import json
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Optional, Type

from crisis_debate.schemas import (
    Argument,
    ArgumentJudgment,
    Claim,
    CriterionScore,
    Option,
    PackageItem,
    Recommendation,
    RoundJudgment,
    Scenario,
)

#: Recorded runs. Everything in here was written by a model, which is why it is
#: kept apart from `eval/` — the study set holds inputs and facts, this holds
#: generated output (CONTRACT.md §5).
CACHE_DIR = Path(__file__).resolve().parents[1] / "demo"


class CacheExhausted(RuntimeError):
    """The pipeline asked for more turns than were recorded."""


def available() -> List[str]:
    return sorted(p.stem for p in CACHE_DIR.glob("*.json"))


def load_cache(scenario_id_or_name: str) -> Dict[str, Any]:
    p = CACHE_DIR / f"{scenario_id_or_name}.json"
    if not p.exists():
        for cand in CACHE_DIR.glob("*.json"):
            if json.loads(cand.read_text(encoding="utf-8")).get("scenario_id") == scenario_id_or_name:
                p = cand
                break
        else:
            raise FileNotFoundError(f"no recorded run for {scenario_id_or_name!r}; have {available()}")
    return json.loads(p.read_text(encoding="utf-8"))


def recorded_priorities(scenario_id_or_name: str, audience: str = "policymaker") -> List[str]:
    """Which objectives this recording can replay for `audience`.

    The console asks so it can grey out the rest: with two objectives chosen
    from six, a user in recorded mode would otherwise pick an unrecorded pair
    and meet CacheExhausted halfway through a run. The failure is honest but it
    is better not to offer the choice than to fail on it.

    Only objectives present in BOTH slots count. A recording that holds a
    baseline but no debate synthesis for an objective would replay B0 and then
    die on B1/B2, which is worse than not offering it.
    """
    try:
        cache = load_cache(scenario_id_or_name)
    except Exception:
        return []
    slots = []
    for slot in ("baseline", "recommendation"):
        src = cache.get(slot)
        if isinstance(src, list):
            slots.append({e.get("priority") for e in src
                          if isinstance(e, dict) and e.get("audience") == audience})
        elif isinstance(src, dict):
            slots.append(None)          # untailored: serves any request
    if not slots:
        return []
    if any(x is None for x in slots):
        return []                        # untailored recording — no restriction
    common = set.intersection(*slots) if slots else set()
    return sorted(p for p in common if p)


def _items(pkg: Dict[str, str]) -> List[PackageItem]:
    return [PackageItem(issue=k, option=v) for k, v in pkg.items()]


#: Rubric criteria renamed since a recording was made, old -> new. The paper
#: scores consistency with the agent's own previous position; recordings from
#: before that fix call the slot by its old name.
RENAMED = {"interest_consistency": "position_consistency"}


@dataclass
class CachedBackend:
    """Serves recorded turns in pipeline order.

    `speed` replays the recorded latency: 0 is instant (the default, and what
    tests use), 1 is real time, 4 is four times faster than the recording.
    """

    scenario: Scenario
    cache: Dict[str, Any]
    speed: float = 0.0
    usage: Dict[str, int] = field(default_factory=lambda: {"input": 0, "output": 0, "calls": 0})
    is_cached: bool = True
    _arg: int = 0
    _judge: int = 0
    _rec: int = 0

    @classmethod
    def for_scenario(cls, scenario: Scenario, speed: float = 0.0) -> "CachedBackend":
        return cls(scenario=scenario, cache=load_cache(scenario.scenario_id), speed=speed)

    def _sleep(self, ms: int) -> None:
        if self.speed > 0 and ms:
            time.sleep(ms / 1000.0 / self.speed)

    def parse(self, *, system: str, user: str, output_format: Type, max_tokens: int = 16000,
              tag: Optional[str] = None):
        self.usage["calls"] += 1

        if output_format is Argument:
            flat = [t for rnd in self.cache["rounds"] for t in rnd]
            if self._arg >= len(flat):
                raise CacheExhausted(
                    f"recorded run has {len(flat)} argument turns; the pipeline asked for "
                    f"{self._arg + 1}. Record more rounds or run with fewer."
                )
            t = flat[self._arg]; self._arg += 1
            self._sleep(t.get("latency_ms", 0))
            return Argument(country=t["country"], position=t["position"],
                            key_claims=[Claim(claim=t["position"], evidence="recorded run")],
                            concessions=[t["concession"]], red_lines=[],
                            proposed_package=_items(t["package"]))

        if output_format is RoundJudgment:
            rec = self.cache["judge"]
            if self._judge >= len(rec):
                raise CacheExhausted(f"recorded run has {len(rec)} judged rounds; asked for {self._judge + 1}.")
            j = rec[self._judge]; self._judge += 1
            self._sleep(j.get("latency_ms", 0))
            return RoundJudgment(
                round_index=j["round_index"],
                judgments=[ArgumentJudgment(
                    country=x["country"],
                    scores=[CriterionScore(criterion=RENAMED.get(k, k), score=v,
                                           justification=x["summary"])
                            for k, v in x["scores"].items()],
                    summary=x["summary"]) for x in j["judgments"]],
                unaddressed_tradeoffs=j["unaddressed"])

        if output_format is Recommendation:
            # The baseline conditions ask for a recommendation without any
            # debate having happened, so they get the recorded baseline; the
            # debate conditions get the recorded synthesis.
            slot = "baseline" if self._arg == 0 else "recommendation"
            src = self._tailored(slot, tag)
            self._rec += 1
            self._sleep(src.get("latency_ms", 0))
            return Recommendation(
                focus_country=self.scenario.focus_country,
                audience=src.get("audience", "policymaker"),
                priority=src.get("priority", "casualty_minimisation"),
                headline=src.get("headline", src["rationale"][:120]),
                options=[Option(condition=o["condition"], action=o["action"],
                                # older recordings wrote this key as "priority"
                                priority_tag=o.get("priority_tag") or o["priority"],
                                requires_concession="see rationale",
                                principal_risk="see rationale") for o in src["options"]],
                rationale=src["rationale"], recommended_package=_items(src["package"]))

        raise AssertionError(f"no recorded response for {output_format!r}")

    def _tailored(self, slot: str, tag: Optional[Any]) -> Dict[str, Any]:
        """The recorded recommendation for this reader and objective.

        Selected by (audience, priority) rather than by call order. Order would
        be wrong in two ways: the caller may request readers in any sequence,
        and the best-of-n baseline draws many samples for the *same* reader,
        which a counter would walk straight off the end of.

        Recordings made before tailoring existed hold a single object, and those
        still serve any request because there is only one thing they can mean.
        A request a *tailored* recording does not hold raises instead of handing
        back another reader's advice relabelled — that would show tailoring the
        system never did, which is the one failure mode this whole feature must
        not have.
        """
        src = self.cache[slot]
        if not isinstance(src, list):
            return src
        if tag is None:
            return src[0]
        audience, priority = tag
        for entry in src:
            if entry.get("audience") == audience and entry.get("priority") == priority:
                return entry
        have = sorted({(e.get("audience"), e.get("priority")) for e in src})
        raise CacheExhausted(
            f"recorded run has no {slot} advice for {audience!r} protecting {priority!r}; "
            f"it holds {have}. Set OPENAI_API_KEY to generate it, or request a "
            f"combination that was recorded."
        )
